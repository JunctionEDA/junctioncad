// gen-cad-registry.mjs — writes the lists of what the mechanical and assembly domains are made of.
//
// A feature, a toolbar tool, a side panel, a worker service or a mate type is one file in its folder with a
// default export.  This script lists those files, so adding one never means editing a shared index (ten people
// adding features at once would all be changing the same lines).  It writes
//
//   web/domains/mechanical/generated/page.ts     features, tools, panels   (the page bundle)
//   web/domains/mechanical/generated/worker.ts   features, services        (the worker bundle)
//   web/domains/assembly/generated/page.ts       mate types, tools, panels
//
// which are not committed (.gitignore): `npm run check`, `npm run build` and the tests run this first.
// A file whose name starts with "_" or ends in ".test.ts" is skipped.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "web", "domains");

function modules(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f) && !/\.d\.ts$/.test(f) && !f.startsWith("_")).sort().map((f) => f.replace(/\.tsx?$/, ""));
}

function write(file, lists) {
  let imports = "", body = "";
  let n = 0;
  for (const { name, type, from, dir, rel } of lists) {
    const names = [];
    for (const m of modules(dir)) { const id = `m${n++}`; imports += `import ${id} from "${rel}/${m}";\n`; names.push(id); }
    body += `export const ${name}: readonly ${type}[] = [${names.join(", ")}];\n`;
    imports = `import type { ${type} } from "${from}";\n` + imports;
  }
  const text = `// GENERATED by scripts/gen-cad-registry.mjs from the files in the folders it lists. Do not edit, do not commit.\n${imports}\n${body}`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
}

const mech = path.join(web, "mechanical"), asm = path.join(web, "assembly");
write(path.join(mech, "generated", "page.ts"), [
  { name: "FEATURES", type: "FeatureDefinition", from: "../core/feature", dir: path.join(mech, "features"), rel: "../features" },
  { name: "TOOLS", type: "ToolDefinition", from: "../core/tool", dir: path.join(mech, "tools"), rel: "../tools" },
  { name: "PANELS", type: "PanelDefinition", from: "../core/tool", dir: path.join(mech, "panels"), rel: "../panels" },
]);
write(path.join(mech, "generated", "worker.ts"), [
  { name: "FEATURES", type: "FeatureDefinition", from: "../core/feature", dir: path.join(mech, "features"), rel: "../features" },
  { name: "SERVICES", type: "ServiceDefinition", from: "../kernel/service", dir: path.join(mech, "services"), rel: "../services" },
]);
write(path.join(asm, "generated", "page.ts"), [
  { name: "MATES", type: "MateDefinition", from: "../core/mate", dir: path.join(asm, "mates"), rel: "../mates" },
  { name: "TOOLS", type: "AssemblyToolDefinition", from: "../core/tool", dir: path.join(asm, "tools"), rel: "../tools" },
]);

// The sketch constraint solver (FreeCAD's PlaneGCS, npm @salusoft89/planegcs, LGPL-2.1-or-later) is a .wasm of
// about 0.5 MB.  It is written out as a module holding the bytes in base64, so the page bundle and the node
// tests carry it without a loader flag or a route on the server (web/domains/mechanical/sketch/solver/load.ts).
{
  const wasm = path.resolve(web, "..", "..", "node_modules", "@salusoft89", "planegcs", "dist", "planegcs_dist", "planegcs.wasm");
  const out = path.join(mech, "generated", "planegcs-wasm.ts");
  const text = `// GENERATED by scripts/gen-cad-registry.mjs from @salusoft89/planegcs. Do not edit, do not commit.\nexport default "${fs.readFileSync(wasm).toString("base64")}";\n`;
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) fs.writeFileSync(out, text);
}
